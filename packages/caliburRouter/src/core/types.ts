/**
 * CalibURRouter 核心类型定义
 * 
 * 基于集合论的类型安全模式匹配引擎的类型系统
 */

import type { Type } from "arktype";

// ============================================================================
// 基础类型
// ============================================================================

/**
 * 模式处理器类型
 * @template 模式 - 输入模式的类型（由arktype推断）
 * @template 结果 - 处理器返回值类型
 */
export type 处理器<模式, 结果> = (输入: 模式) => 结果;

/**
 * 已注册的模式-处理器对
 */
export interface 已注册模式<模式 = unknown, 结果 = unknown> {
    /** arktype模式定义 */
    模式: Type<模式>;
    /** 对应的处理器 */
    处理器: 处理器<模式, 结果>;
}

/**
 * 分发器函数类型
 * @template 输入 - 输入类型（全集）
 * @template 输出 - 所有处理器返回类型的联合
 */
export type 分发器<输入, 输出> = (输入: 输入) => 输出;

// ============================================================================
// 类型工具
// ============================================================================

/**
 * 从剩余集中排除已切割的模式
 * 这是类型级别的集合差运算
 */
export type 切割后剩余<剩余集, 已切割模式> = Exclude<剩余集, 已切割模式>;

/**
 * 检查剩余集是否为空（never）
 */
export type 剩余集为空<剩余集> = [剩余集] extends [never] ? true : false;

/**
 * 深度合并类型：将全集与模式合并
 * - 模式中指定的属性使用模式中更窄的类型（类型收窄）
 * - 模式中未指定的属性保留全集中的类型
 * 
 * 这允许用户只用部分属性定义模式，同时处理器能享受类型收窄并访问全集的所有属性
 * 
 * @example
 * type 全集 = { 名称: string, 等级: number }
 * type 模式 = { 等级: 10 }  // 只指定等级
 * type 合并后 = 合并类型<全集, 模式>
 * // = { 名称: string, 等级: 10 }  // 名称保留，等级收窄
 */
export type 合并类型<全集, 模式> =
    全集 extends object
    ? 模式 extends object
    ? {
        // 对于全集中的每个键
        [K in keyof 全集]: K extends keyof 模式
        // 如果模式中也有这个键，递归合并（支持嵌套对象）
        ? 合并类型<全集[K], 模式[K]>
        // 否则保留全集中的类型
        : 全集[K]
    }
    // 如果模式不是对象，直接使用模式类型（类型收窄）
    : 模式
    // 如果全集不是对象，使用模式类型（类型收窄）
    : 模式;

// ============================================================================
// 匹配器构建器接口
// ============================================================================

/**
 * 匹配器构建器接口
 * 提供链式API用于定义模式分发规则
 * 
 * @template 全集 - 全集类型
 * @template 剩余集 - 当前剩余类型
 * @template 结果联合 - 当前结果类型联合
 */
export interface 匹配器构建器<全集, 剩余集, 结果联合> {
    /**
     * 切割子集并注册处理器
     * 类型系统会自动从剩余集中排除已切割的模式
     * 
     * @param 模式 - arktype模式定义（用于匹配筛选，可以只指定部分属性）
     * @param 处理器 - 匹配该模式时的处理函数
     *   - 处理器接收合并后的类型：模式中的属性使用收窄后的类型，其他属性保留全集类型
     *   - 这允许只用部分属性定义模式，同时享受类型收窄并访问全集的所有属性
     * @returns 更新后的匹配器构建器（剩余集已缩小）
     */
    split<模式定义, 新结果>(
        模式: Type<模式定义>,
        // 处理器接收合并类型：模式中的属性收窄，其他属性保留全集类型
        处理器: 处理器<合并类型<全集, 模式定义>, 新结果>
    ): 匹配器构建器<全集, 切割后剩余<剩余集, 模式定义>, 结果联合 | 新结果>;

    /**
     * 处理剩余模式
     * 当其他split都不匹配时调用
     * 
     * @param 处理器 - 处理剩余模式的函数（接收完整的全集类型输入）
     * @returns 可构建的匹配器
     */
    remain<新结果>(
        // 处理器接收全集类型，因为运行时传入的是符合全集的完整对象
        处理器: 处理器<全集, 新结果>
    ): 可构建匹配器<全集, 结果联合 | 新结果>;

    /**
     * 构建分发器（运行时可用，但类型层面会根据使用方式提供警告）
     */
    build(): 分发器<全集, 结果联合>;
}

/**
 * 可构建的匹配器（已处理所有模式）
 */
export interface 可构建匹配器<全集, 结果联合> {
    /**
     * 构建最终的分发器函数
     */
    build(): 分发器<全集, 结果联合>;
}

// ============================================================================
// 工具类型导出
// ============================================================================

/**
 * 从arktype Type中提取推断类型
 */
export type 推断类型<T extends Type> = T extends Type<infer U> ? U : never;
