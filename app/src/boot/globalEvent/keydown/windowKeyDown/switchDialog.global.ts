/**
 * 用途：集中保存窗口级切换对话框的当前实例，供键盘入口与点击事件处理器共享。
 * 使用范围：仅限 `windowKeyDown` 目录及其协作者读取/更新当前切换对话框实例。
 * 解耦评估：这里承载的是窗口级共享 UI 状态，理论上可继续升级为更正式的 dialog store；
 * 但在当前目录内先收敛成单点全局模块，已经比散落在入口文件中直接共享变量更低耦合。
 */

/**
 * 用途：引入对话框类型，约束共享状态只能保存切换对话框实例或空值。
 * 使用范围：仅用于当前文件的共享状态变量与写入函数类型标注。
 * 解耦评估：这是纯类型依赖，不形成运行时耦合；通过同层网关复用即可。
 */
import type { Dialog } from "./imports";

/**
 * 当前切换对话框实例。
 */
export let switchDialog: Dialog | undefined;

/**
 * 作用：更新当前激活的切换对话框实例。
 * 意图：把切换对话框状态写入收敛到单个入口，避免多个执行器直接操作共享变量。
 * 调用时机：创建切换对话框后写入，销毁或关闭后清空。
 * 问题/改进：当前仍是单窗口单实例模型；若未来需要支持多窗口并发切换，可改为按窗口 ID 存储。
 */
/** @同步豁免: 生命周期 */
export const setSwitchDialog = (dialog: Dialog | undefined) => {
    switchDialog = dialog;
};
