/**
 * 说明数学公式渲染的提示词
 * @returns 
 * @同步豁免: 性能考虑 - 纯字符串返回函数，异步化会引入不必要的 Promise 开销且调用方在模板字符串中同步拼接。
 * @显式返回类型原因: 固定返回常量字符串，显式标注便于调用方在模板字面量中直接使用。
 */
export function getMathSection(): string {
	return `## 数学公式渲染

使用 math 代码块可以渲染数学公式。支持 LaTeX 语法：

### 行内数学公式
行内公式使用单个 $ 包裹,内部使用LaTeX支持的格式即可
### 块级数学公式
块级公式使用两个 $$ 包裹,内部使用LateX标准语法即可
注意语言为math的代码块并不会被渲染为公式,当需要展示公式而不是latex语法时你应该使用$$语法
数学公式将自动渲染并显示在文档中，支持缩放和交互。
`;
}